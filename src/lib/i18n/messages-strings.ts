const STRINGS = { EN: en, FR: fr, AR: ar };

export function useMessagesStrings(): MessagesStrings {
  const { lang } = useLanguage();
  return STRINGS[lang] ?? en;
}

/** Display name of a channel, as the web inbox shows it. */
export function providerName(provider: string) {
  if (provider === 'BOOKING_COM') return 'Booking.com';
  if (provider === 'AIRBNB') return 'Airbnb';
  if (provider === 'EXPEDIA') return 'Expedia';
  return provider;
}
