const all = { EN: en, FR: fr, AR: ar };

export function useDeskStrings(): DeskStrings {
  const { lang } = useLanguage();
  return all[lang as keyof typeof all] ?? en;
}

/** "1 250 MAD" in the app's language. */
export function formatMad(n: number, lang: string) {
  const v = n.toLocaleString(lang === 'FR' ? 'fr-FR' : lang === 'AR' ? 'ar-MA' : 'en-GB', { maximumFractionDigits: 2 });
  return `${v} MAD`;
}
